"""The whitelist settings written into the filter file itself, so the Whitelist tab can open the file again
and edit it. Pure (stdlib only): the game ignores comment lines, and every line starts with "#" and is plain
ASCII (compressed JSON as base64, cut into short lines).

    # poe-checker-config: <chunk>        (one or more lines, joined in file order)
"""
from __future__ import annotations
import base64
import json
import re
import zlib
from typing import Optional

MARK = "# poe-checker-config:"
SCHEMA = 1
_CHUNK = 110
# the first line of every whitelist file we write (a file with this but no embedded config is from a build
# that did not embed yet); the tier tab's header marks the other kind of file we write
WL_HEADER = "# === PoE Checker - Whitelist"
TIER_HEADER_START = "# Generated by PoE Price & Trade Checker"

# the config keys that make up a whitelist (per game where it matters)
_GAME_KEYS = ("wl_item_tier", "wl_cat_tier", "wl_class_tier", "wl_unique_tier", "wl_block_tier", "wl_rarity_rows", "wl_equip_rows", "wl_lists", "wl_item_stack",
              "whitelist_gem_uncut", "whitelist_gem_names", "whitelist_custom")
_SHARED_KEYS = ("wl_v2", "wl_tier_format", "wl_tier_stack", "wl_tier_style", "whitelist_gold", "whitelist_gold_min", "wl_map_on",
                "wl_map_tier_min", "wl_map_rarity_min", "whitelist_gem_tier")


def config_keys(game: str) -> list:
    return list(_SHARED_KEYS) + [f"{k}_{game}" for k in _GAME_KEYS]


def whitelist_part(cfg: dict, game: str) -> dict:
    """Just the whitelist keys of a filter_gen config dict."""
    return {k: cfg[k] for k in config_keys(game) if k in cfg}


def embed_lines(cfg: dict, game: str, version: str = "") -> list:
    payload = {"schema": SCHEMA, "game": game, "app": version, "cfg": whitelist_part(cfg, game)}
    raw = json.dumps(payload, ensure_ascii=True, sort_keys=True, separators=(",", ":")).encode("ascii")
    b64 = base64.b64encode(zlib.compress(raw, 9)).decode("ascii")
    return [f"{MARK} {b64[i:i + _CHUNK]}" for i in range(0, len(b64), _CHUNK)]


def embed(text: str, cfg: dict, game: str, version: str = "") -> str:
    """`text` (a whitelist filter) + the settings as comment lines at its end."""
    body = text.rstrip("\n")
    return body + "\n\n# settings of this filter (the Whitelist tab reads them back; the game ignores them)\n" \
        + "\n".join(embed_lines(cfg, game, version)) + "\n"


def extract(text: str) -> Optional[dict]:
    """The embedded {"schema", "game", "app", "cfg"} of a filter file, or None (no config / unreadable)."""
    chunks = [m.group(1) for m in (re.match(r"^" + re.escape(MARK) + r"\s*(\S+)\s*$", l) for l in text.splitlines())
              if m]
    if not chunks:
        return None
    try:
        data = json.loads(zlib.decompress(base64.b64decode("".join(chunks).encode("ascii"))).decode("ascii"))
    except Exception:
        return None
    if not isinstance(data, dict) or not isinstance(data.get("cfg"), dict) or data.get("game") not in ("poe1", "poe2"):
        return None
    return data


def classify(text: str) -> str:
    """"ok" (has settings) | "no_config" (a whitelist file from before settings were embedded) |
    "tier" (the NeverSink tab's file) | "foreign" (not made by this program)."""
    if extract(text) is not None:
        return "ok"
    head = text[:600]
    if WL_HEADER in head:
        return "no_config"
    if TIER_HEADER_START in head:
        return "tier"
    return "foreign"
